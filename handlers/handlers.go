const UserDataPath = "user_data"

type podcastList struct {
	Podcasts []podcast.Podcast `json:"podcasts"`
}

// addPodcastRequest documents the expected AddPodcast request body.
type addPodcastRequest struct {
	// RSSUrl may be a direct RSS feed URL, or an Apple Podcasts show URL
	// (e.g. https://podcasts.apple.com/us/podcast/the-daily/id1200361736),
	// which is automatically resolved to its RSS feed via Apple's iTunes
	// Lookup API.
	RSSUrl string `json:"rss_url"`
}

// Handler holds shared dependencies for all route handlers.
type Handler struct {
	config podcast.Config
	pw     *podcast.PodcastWatcher
	db     *gorm.DB
}

func New(config podcast.Config, pw *podcast.PodcastWatcher, db *gorm.DB) *Handler {
	return &Handler{config: config, pw: pw, db: db}
}

// Register attaches all public-facing routes to the given Echo instance.
func (h *Handler) Register(e *echo.Echo) {
	e.GET("/refresh", h.Refresh)

	e.GET("/podcasts", h.ListPodcasts)
	e.POST("/podcasts", h.AddPodcast)
	e.GET("/podcasts/:podcast_id", h.GetPodcast)
	e.GET("/podcasts/:podcast_id/image", h.GetPodcastImage)
	e.GET("/podcasts/:podcast_id/episodes/:episode_id/stream", h.StreamEpisode)

	e.GET("/rss/all", h.RSSAll)

	e.GET("/ads/candidates", h.ListAdCandidates)
	e.POST("/ads/rescan-fingerprints", h.RescanFingerprints)

	e.GET("/openapi.json", h.OpenAPISpec)
	e.GET("/doc", h.APIDocs)
	e.GET("/docs", h.APIDocs)
	e.GET("/doc/redoc.standalone.js", h.RedocBundle)

	e.GET("/metrics", h.Metrics)

	// These status endpoints are not intended to provide secure user data management.
	// The only data stored are podcast status, played, etc. In the intended local
	// network environment, a simple shared token generated by the client is used.
	// If lost, this token can't be recovered from the server side.
	e.GET("/client-status/:key-id", h.GetClientStatus)
	e.PUT("/client-status/:key-id", h.PutClientStatus)
	e.DELETE("/client-status/:key-id", h.DeleteClientStatus)
}

// RegisterInternal attaches the internal worker job API to the given Echo
// instance. This is served on a separate port/listener from the public
// routes (see cmd/server/main.go), so it can be exposed only via a
// cluster-internal Service and never through the public Ingress, without
// relying on path-based access control.
func (h *Handler) RegisterInternal(e *echo.Echo) {
	e.POST("/internal/jobs/claim", h.ClaimJob)
	e.POST("/internal/jobs/:job_id/complete", h.CompleteJob)
	e.POST("/internal/jobs/:job_id/upload", h.UploadJobAudio)
	e.GET("/internal/jobs/queue-length", h.QueueLength)
}

func (h *Handler) EnqueueAll() {
	if !h.pw.QueueEmpty() {
		klog.Infof("podcasts still in update queue, skipping cron update")
		return
	}
	podcasts, err := h.pw.ListPodcasts()
	if err != nil {
		klog.Errorf("error listing podcasts on refresh: %s", err)
		return
	}
	for _, p := range podcasts {
		h.pw.EnqueuePodcast(p)
	}
}

// Refresh godoc
// @Summary      Refresh all podcasts
// @Description  Enqueues every known podcast for a background RSS/episode sync.
// @Tags         podcasts
// @Produce      json
// @Success      200  {object}  map[string]string
// @Router       /refresh [get]
func (h *Handler) Refresh(c echo.Context) error {
	h.EnqueueAll()
	return c.JSON(http.StatusOK, map[string]string{"status": "ok"})
}

// ListPodcasts godoc
// @Summary      List subscribed podcasts
// @Description  Returns all subscribed podcasts with episode lists omitted.
// @Tags         podcasts
// @Produce      json
// @Success      200  {object}  podcastList
// @Failure      500  {object}  map[string]string
// @Router       /podcasts [get]
func (h *Handler) ListPodcasts(c echo.Context) error {
	podcasts, err := h.pw.ListPodcasts()
	if err != nil {
		klog.Errorf("error listing podcasts: %s", err)
		return c.String(http.StatusInternalServerError, `{"error": "error listing podcasts"}`)
	}

	for idx := range podcasts {
		podcasts[idx].Episodes = nil
	}

	return c.JSON(http.StatusOK, podcastList{Podcasts: podcasts})
}

// AddPodcast godoc
// @Summary      Subscribe to a podcast
// @Description  Adds a podcast subscription from an RSS feed URL and queues it for sync.
// @Tags         podcasts
// @Accept       json
// @Produce      json
// @Param        request  body      addPodcastRequest  true  "RSS feed URL, or an Apple Podcasts show URL to auto-resolve"
// @Success      200      {object}  podcast.Podcast
// @Failure      400      {object}  map[string]string
// @Router       /podcasts [post]
func (h *Handler) AddPodcast(c echo.Context) error {
	jsonData := make(map[string]interface{})
	if err := json.NewDecoder(c.Request().Body).Decode(&jsonData); err != nil {
		klog.Errorf("error reading json request: %s", err)
		return c.String(http.StatusBadRequest, `{"error": "invalid request"}`)
	}

	rssUrl, ok := jsonData["rss_url"]
	if !ok {
		return c.String(http.StatusBadRequest, `{"error": "rss_url must be provided in json request body"}`)
	}

	podcastData, err := podcast.AddPodcast(h.config, h.db, rssUrl.(string))
	if err != nil {
		klog.Errorf("error processing podcast rss url %s: %s", rssUrl.(string), err)
		return c.String(http.StatusBadRequest, `{"error": "error processing podcast rss url"}`)
	}

	h.pw.InvalidateCache()
	h.pw.EnqueuePodcast(*podcastData)

	return c.JSON(http.StatusOK, podcastData)
}

// GetPodcast godoc
// @Summary      Get a podcast
// @Description  Returns a single subscribed podcast, including its episode list.
// @Tags         podcasts
// @Produce      json
// @Param        podcast_id  path      string  true  "Podcast ID"
// @Success      200         {object}  podcast.Podcast
// @Failure      500         {object}  map[string]string
// @Router       /podcasts/{podcast_id} [get]
func (h *Handler) GetPodcast(c echo.Context) error {
	podcastData, err := h.pw.GetPodcast(c.Param("podcast_id"))
	if err != nil {
		klog.Errorf("error getting podcast: %s", err)
		return c.String(http.StatusInternalServerError, `{"error": "error getting podcast"}`)
	}

	return c.JSON(http.StatusOK, podcastData)
}

// GetPodcastImage godoc
// @Summary      Get a podcast's cover image
// @Description  Returns the cached cover image file for a podcast.
// @Tags         podcasts
// @Produce      image/*
// @Param        podcast_id  path  string  true  "Podcast ID"
// @Success      200
// @Failure      500  {object}  map[string]string
// @Router       /podcasts/{podcast_id}/image [get]
func (h *Handler) GetPodcastImage(c echo.Context) error {
	podcastData, err := h.pw.GetPodcast(c.Param("podcast_id"))
	if err != nil {
		klog.Errorf("error getting podcast: %s", err)
		return c.String(http.StatusInternalServerError, `{"error": "error getting podcast"}`)
	}

	imagePath := podcastData.GetImage(h.config)

	c.Response().Status = http.StatusOK
	c.Response().Header().Set("Cache-Control", "max-age=604800")
	http.ServeFile(c.Response().Writer, c.Request(), imagePath)
	return nil
}

// streamRetryAfterSec is suggested to clients as how long to wait before
// retrying a 503 from StreamEpisode - long enough for a requeued download
// job to typically be picked up and completed, short enough that the
// client doesn't feel stuck.
const streamRetryAfterSec = 15

// streamUnavailableResponse is returned (as a 503) when StreamEpisode can't
// serve the file immediately. Retrying is true when a re-download was
// successfully queued (the client should retry shortly); false means the
// requeue itself failed, so retrying right away is unlikely to help.
type streamUnavailableResponse struct {
	Error    string `json:"error"`
	Retrying bool   `json:"retrying"`
}

func (h *Handler) streamUnavailable(c echo.Context, podcastID, episodeID, reason string) error {
	retrying := h.requeueWithWarn(podcastID, episodeID)

	msg := fmt.Sprintf("%s; a re-download has been queued, retry in a few seconds", reason)
	if !retrying {
		msg = fmt.Sprintf("%s; re-download could not be queued, try again later", reason)
	}

	c.Response().Header().Set("Retry-After", strconv.Itoa(streamRetryAfterSec))
	return c.JSON(http.StatusServiceUnavailable, streamUnavailableResponse{Error: msg, Retrying: retrying})
}

// StreamEpisode godoc
// @Summary      Stream an episode's audio
// @Description  Streams the downloaded audio file for a podcast episode, requeuing a redownload if the file is missing or invalid.
// @Tags         podcasts
// @Produce      audio/mpeg
// @Param        podcast_id  path  string  true  "Podcast ID"
// @Param        episode_id  path  string  true  "Episode ID"
// @Success      200
// @Failure      500  {object}  map[string]string
// @Failure      503  {object}  streamUnavailableResponse
// @Router       /podcasts/{podcast_id}/episodes/{episode_id}/stream [get]
func (h *Handler) StreamEpisode(c echo.Context) error {
	podcastID := c.Param("podcast_id")
	episodeID := c.Param("episode_id")

	// Resolved via a lean single-row query (not h.pw.GetPodcast, which
	// would Preload every episode for the podcast) - see
	// podcast.GetEpisodeAudioFilePath.
	filePath, err := podcast.GetEpisodeAudioFilePath(h.db, h.config, podcastID, episodeID)
	if err != nil {
		klog.Errorf("error getting audio file for episode %s/%s: %s", podcastID, episodeID, err)
		return c.String(http.StatusInternalServerError, `{"error": "error getting stream"}`)
	}

	// Validate the file is readable, non-empty, and actually audio (not an HTML/text error page).
	info, err := os.Stat(filePath)
	if err != nil || info.Size() == 0 {
		klog.Warningf("audio file missing or empty for episode %s/%s (%s), requeuing for download",
			podcastID, episodeID, filePath)
		return h.streamUnavailable(c, podcastID, episodeID, "episode audio not downloaded yet")
	}

	if err := podcast.ValidateAudioFile(filePath); err != nil {
		klog.Warningf("audio file invalid for episode %s/%s (%s): %s — requeuing for download",
			podcastID, episodeID, filePath, err)
		os.Remove(filePath)
		return h.streamUnavailable(c, podcastID, episodeID, "episode audio file was invalid")
	}

	c.Response().Status = http.StatusOK
	http.ServeFile(c.Response().Writer, c.Request(), filePath)
	return nil
}

// RSSAll godoc
// @Summary      Combined RSS feed
// @Description  Returns a single RSS feed aggregating all subscribed podcasts' episodes.
// @Tags         rss
// @Produce      xml
// @Success      200  {string}  string
// @Failure      500  {object}  map[string]string
// @Router       /rss/all [get]
func (h *Handler) RSSAll(c echo.Context) error {
	podcasts, err := h.pw.ListPodcasts()
	if err != nil {
		klog.Errorf("error getting podcasts for rss: %s", err)
		return c.String(http.StatusInternalServerError, `{"error": "error getting podcast"}`)
	}

	host := c.Request().Header.Get("X-Forwarded-Host")
	scheme := c.Request().Header.Get("X-Forwarded-Proto")

	if host == "" {
		host = c.Request().Host
	}
	if scheme == "" {
		scheme = c.Request().URL.Scheme
	}
	if scheme == "" {
		scheme = "http"
	}

	rss, err := podcast.RenderPodcasts(podcasts, scheme+"://"+host)
	if err != nil {
		klog.Errorf("error rendering rss feed: %s", err)
		return c.String(http.StatusInternalServerError, `{"error": "error getting rss feed"}`)
	}

	return c.Blob(http.StatusOK, "application/rss+xml", []byte(rss))
}

func (h *Handler) clientInfo(c echo.Context) (key string, filePath string) {
	token := strings.Replace(c.Request().Header.Get("Authorization"), "Basic ", "", 1)
	key = c.Param("key-id")
	hashedToken := fmt.Sprintf("%x", sha256.Sum256([]byte(token+key)))
	filePath = filepath.Join(h.config.FileHome, UserDataPath, hashedToken)
	return
}

// GetClientStatus godoc
// @Summary      Get client status blob
// @Description  Returns a client-stored status blob (e.g. playback progress) identified by a client-generated key.
// @Tags         client-status
// @Produce      plain
// @Param        key-id  path  string  true  "Client status key"
// @Success      200
// @Failure      404  {object}  map[string]string
// @Failure      500  {object}  map[string]string
// @Router       /client-status/{key-id} [get]
func (h *Handler) GetClientStatus(c echo.Context) error {
	key, filePath := h.clientInfo(c)

	if _, err := os.Stat(filePath); errors.Is(err, os.ErrNotExist) {
		return c.JSONBlob(http.StatusNotFound, []byte(`{"error": "key not found"}`))
	} else if err != nil {
		klog.Errorf("error fetching client status key %s: %s", key, err)
		return c.JSONBlob(http.StatusInternalServerError, []byte(`{"error": "internal server error"}`))
	}

	f, err := os.Open(filePath)
	if err != nil {
		klog.Errorf("error opening client status key %s: %s", key, err)
		return c.JSONBlob(http.StatusInternalServerError, []byte(`{"error": "internal server error"}`))
	}
	defer f.Close()

	byteValue, err := ioutil.ReadAll(f)
	if err != nil {
		klog.Errorf("error reading client status key %s: %s", key, err)
		return c.JSONBlob(http.StatusInternalServerError, []byte(`{"error": "internal server error"}`))
	}

	c.Response().Header().Add(echo.HeaderContentType, "text/plain")
	c.Response().Header().Add("Cache-Control", "no-cache")
	_, err = c.Response().Write(byteValue)
	return err
}

// PutClientStatus godoc
// @Summary      Store client status blob
// @Description  Stores/overwrites a client-stored status blob identified by a client-generated key.
// @Tags         client-status
// @Accept       plain
// @Produce      json
// @Param        key-id   path  string  true  "Client status key"
// @Success      200      {object}  map[string]string
// @Failure      500      {object}  map[string]string
// @Router       /client-status/{key-id} [put]
func (h *Handler) PutClientStatus(c echo.Context) error {
	key, filePath := h.clientInfo(c)

	data, err := ioutil.ReadAll(c.Request().Body)
	if err != nil {
		klog.Errorf("error reading data while updating client status key %s: %s", key, err)
		return c.JSONBlob(http.StatusInternalServerError, []byte(`{"error": "internal server error"}`))
	}

	if err = ioutil.WriteFile(filePath, data, 0764); err != nil {
		klog.Errorf("error writing data while updating client status key: %s", key)
		return c.JSONBlob(http.StatusInternalServerError, []byte(`{"error": "internal server error"}`))
	}

	return c.JSONBlob(http.StatusOK, []byte(`{"status": "success"}`))
}

// DeleteClientStatus godoc
// @Summary      Delete client status blob
// @Description  Deletes a client-stored status blob identified by a client-generated key.
// @Tags         client-status
// @Produce      json
// @Param        key-id  path  string  true  "Client status key"
// @Success      200     {object}  map[string]string
// @Failure      500     {object}  map[string]string
// @Router       /client-status/{key-id} [delete]
func (h *Handler) DeleteClientStatus(c echo.Context) error {
	key, filePath := h.clientInfo(c)

	if err := os.Remove(filePath); err != nil {
		klog.Errorf("error removing client status key %s: %s", key, err)
		return c.JSONBlob(http.StatusInternalServerError, []byte(`{"error": "internal server error"}`))
	}

	return c.JSONBlob(http.StatusOK, []byte(`{"status": "success"}`))
}

func (h *Handler) requeueWithWarn(podcastID, episodeID string) bool {
	if err := h.pw.RequeueEpisodeDownload(podcastID, episodeID); err != nil {
		klog.Errorf("requeue failed for episode %s/%s: %s", podcastID, episodeID, err)
		return false
	}
	return true
}
